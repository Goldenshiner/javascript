const month = 2;

switch (month) {
  case 1:
    console.log("January");
    break;
  case 2:
    console.log("february");
    break;
  case 3:
    console.log("march");
    break;
  case 4:
    console.log("april");
    break;
 
  default:
    console.log("not a valid month");
}